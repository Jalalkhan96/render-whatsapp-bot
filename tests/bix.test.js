'use strict';
const assert = require('assert');
const fs = require('fs');
const plugin = fs.readFileSync('plugins/bix.js','utf8');
const router = fs.readFileSync('lib/bixRouter.js','utf8');
const index = fs.readFileSync('index.js','utf8');
assert.ok(/command:\s*['"]bix['"]/.test(plugin));
assert.ok(/aliases:\s*\[[^\]]*['"]abix['"]/.test(plugin));
for (const trigger of ['@bix','-@bix','-bix']) assert.ok(router.includes(trigger), `missing BIX trigger: ${trigger}`);
assert.ok(router.includes('handleDirectBix'));
assert.ok(index.includes("require('./plugins/setbio')"));
assert.ok(index.includes('setBixRuntimeSocket'));
assert.ok(index.includes('AutoBio skipped'));
assert.ok(fs.readFileSync('lib/bix/bixAI.js','utf8').includes('export async function isBixReady'));
assert.ok(router.includes('isBixReady(4000)'));
console.log('[PASS] BIX routing/owner-safe startup integration');
