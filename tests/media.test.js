'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const gif = fs.readFileSync(path.join(__dirname,'../plugins2/gif2sticker.js'),'utf8');
const neko = fs.readFileSync(path.join(__dirname,'../plugins/nekogif.js'),'utf8');
const google = fs.readFileSync(path.join(__dirname,'../plugins2/googleImageSearch.js'),'utf8');
const gimage = fs.readFileSync(path.join(__dirname,'../plugins/gimage.js'),'utf8');
assert.ok(gif.includes('animatedWebpFromBuffer'));
assert.ok(gif.includes("command: 's'"));
assert.ok(gif.includes('Reply to a GIF'));
assert.ok(!fs.readFileSync(path.join(__dirname,'../plugins2/sticker.js'),'utf8').includes("aliases:['s'"));
assert.ok(gif.includes('documentMessage'));
assert.ok(neko.includes("mimetype: 'video/mp4'"));
assert.ok(neko.includes('stickerMode'));
assert.ok(neko.includes('requireFfmpegPath'));
assert.ok(neko.includes('toPlayableMp4'));
