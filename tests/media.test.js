assert.ok(!fs.readFileSync(path.join(__dirname,'../plugins2/image.js'),'utf8').includes("command: 'image'"));
assert.ok(!gimage.includes("'googleimage'"));
console.log('[PASS] media paths: playable Nekogif + animated sticker + single Google image command');
