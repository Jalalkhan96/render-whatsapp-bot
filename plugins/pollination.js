module.exports = {
  command: 'pollination',
  aliases: ['pollinate'],
  category: 'ai',
  description: 'Generate beautiful images using Pollinations AI',
  usage: '.pollination <prompt>',
  async handler(sock, message, args, context = {}) {
    const chatId = context.chatId || message.key.remoteJid;
    const prompt = args.join(' ');

    if (!prompt) {
      return await sock.sendMessage(chatId, { text: '❌ Bhai prompt to do! (e.g. .imagine A cute cat in space)' }, { quoted: message });
    }

    await sock.sendMessage(chatId, { text: '🎨 *Drawing kar raha hoon, bas thodi der...*' }, { quoted: message });

    try {
      const url = `https://image.pollinations.ai/prompt/${encodeURIComponent(prompt)}?width=1024&height=1024&nologo=true`;
      
      await sock.sendMessage(chatId, { 
        image: { url: url }, 
        caption: `✨ *Prompt:* ${prompt}\n\n🎨 *Generated by ABIX-AE (Pollination)*` 
      }, { quoted: message });

    } catch (err) {
      console.log('Pollination error:', err.message);
      await sock.sendMessage(chatId, { text: 'Oops! 😅 AI saste nashe mein hai, thodi der baad try karo!' }, { quoted: message });
    }
  }
};
